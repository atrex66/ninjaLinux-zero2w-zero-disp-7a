#!/usr/bin/env python3
"""Install the prepared private kernel for one-shot tryboot; never reboot.

Run on the Pi as root: install-test-kernel.py /home/magor/kernel-tests/ahalirq1
Requires an artifact manifest generated by this test's build procedure.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import time

VERSION = "6.18.50-ahalirq1"
BOOT = Path("/boot/firmware")
GUARD = "ahal-irq-test-rollback"


def run(*args):
    subprocess.run(args, check=True)


def main():
    assert os.geteuid() == 0
    artifacts = Path(sys.argv[1]).resolve()
    assert "Raspberry Pi Zero 2 W" in Path("/proc/device-tree/model").read_text()
    assert os.uname().release == "6.18.50+rpt-rpi-v8-rt"
    assert BOOT.is_mount()
    manifest = json.loads((artifacts / "artifacts.json").read_text())
    assert manifest["kernelrelease"] == VERSION
    for name, digest in manifest["sha256"].items():
        assert "/" not in name and name not in (".", "..")
        with (artifacts / name).open("rb") as stream:
            assert hashlib.file_digest(stream, "sha256").hexdigest() == digest, name
    module_dir = Path("/lib/modules") / VERSION
    assert not module_dir.exists()
    assert not (BOOT / "tryboot.txt").exists()
    assert not (BOOT / "autoboot.txt").exists()
    targets = [BOOT / "kernel8_ahalirq1.img", BOOT / "initramfs8_ahalirq1",
               BOOT / "cmdline-ahalirq1.txt", Path("/boot") / ("config-" + VERSION),
               Path("/boot") / ("System.map-" + VERSION),
               Path("/usr/local/libexec") / GUARD,
               Path("/etc/systemd/system") / (GUARD + ".service"),
               Path("/etc/systemd/system") / (GUARD + ".timer")]
    assert not any(p.exists() for p in targets), "Refuse to overwrite an earlier test"
    config = (BOOT / "config.txt").read_text()
    cmdline = (BOOT / "cmdline.txt").read_text().strip()
    assert config.count("kernel=kernel8_rt.img") == 1
    assert config.count("initramfs initramfs8_rt followkernel") == 1
    assert "panic=" not in cmdline and "ahal_irq_test=" not in cmdline
    backup = Path("/var/backups/automation-hal") / time.strftime("irq-kernel-%Y%m%d-%H%M%S")
    backup.mkdir(parents=True)
    for name in ("config.txt", "cmdline.txt", "kernel8_rt.img", "initramfs8_rt"):
        shutil.copy2(BOOT / name, backup / name)
    (backup / "installation-manifest.json").write_text(json.dumps(manifest, indent=2))
    print("BACKUP", backup, flush=True)

    # A private module directory; original distro kernel/modules stay intact.
    with tarfile.open(artifacts / "modules.tar.gz", "r:gz") as archive:
        for item in archive.getmembers():
            parts = Path(item.name).parts
            assert parts[:3] == ("lib", "modules", VERSION), item.name
            assert ".." not in parts and not item.issym() and not item.islnk()
            assert item.isfile() or item.isdir()
        archive.extractall("/", filter="data")
    shutil.copy2(artifacts / "config", Path("/boot") / ("config-" + VERSION))
    shutil.copy2(artifacts / "System.map", Path("/boot") / ("System.map-" + VERSION))
    run("depmod", "-a", VERSION)
    run("mkinitramfs", "-o", str(BOOT / "initramfs8_ahalirq1"), VERSION)
    shutil.copy2(artifacts / "Image.gz", BOOT / "kernel8_ahalirq1.img")
    (BOOT / "cmdline-ahalirq1.txt").write_text(cmdline + " panic=10 ahal_irq_test=1\n")
    trial = config.replace("kernel=kernel8_rt.img", "kernel=kernel8_ahalirq1.img")
    trial = trial.replace("initramfs initramfs8_rt followkernel", "initramfs initramfs8_ahalirq1 followkernel")
    trial = trial.replace("auto_initramfs=1", "auto_initramfs=0")
    trial += "\n[all]\ncmdline=cmdline-ahalirq1.txt\nkernel_watchdog_timeout=120\n"

    # If userspace starts but SSH/network does not, return to the original boot.
    script = Path("/usr/local/libexec") / GUARD
    script.write_text('#!/bin/sh\nset -eu\n'
                      'if [ "$(uname -r)" = "' + VERSION + '" ] && '
                      '[ ! -e /run/ahal-irq-test-confirmed ]; then\n'
                      '    date -Is >> /home/magor/kernel-tests/ahalirq1/rollback.log\n'
                      '    uname -a >> /home/magor/kernel-tests/ahalirq1/rollback.log\n'
                      '    logger -t ahal-irq-test "Unconfirmed test boot; returning to normal kernel"\n'
                      '    systemctl reboot\nfi\n')
    script.chmod(0o755)
    units = Path("/etc/systemd/system")
    (units / (GUARD + ".service")).write_text(
        "[Unit]\nDescription=Return from unconfirmed Automation HAL test kernel\n"
        "ConditionKernelCommandLine=ahal_irq_test=1\n[Service]\nType=oneshot\n"
        "ExecStart=/usr/local/libexec/" + GUARD + "\n")
    (units / (GUARD + ".timer")).write_text(
        "[Unit]\nDescription=Bounded Automation HAL kernel boot trial\n"
        "ConditionKernelCommandLine=ahal_irq_test=1\n[Timer]\nOnBootSec=180s\n"
        "AccuracySec=1s\n[Install]\nWantedBy=timers.target\n")
    run("systemctl", "daemon-reload")
    run("systemctl", "enable", GUARD + ".timer")
    # Write tryboot selection last, only after the artifacts and guard exist.
    (BOOT / "tryboot.txt").write_text(trial)
    os.sync()
    assert (BOOT / "config.txt").read_text() == config
    assert (BOOT / "cmdline.txt").read_text().strip() == cmdline
    (artifacts / "installed.json").write_text(json.dumps({
        "kernelrelease": VERSION, "backup": str(backup),
        "normal_boot_unchanged": True, "tryboot": str(BOOT / "tryboot.txt"),
        "confirmation": "touch /run/ahal-irq-test-confirmed; systemctl stop ahal-irq-test-rollback.timer",
    }, indent=2) + "\n")
    print("READY: one-shot boot via: reboot '0 tryboot'", flush=True)


if __name__ == "__main__":
    main()
